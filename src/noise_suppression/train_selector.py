"""Train the supervised filter selector from sweep results.

Steps:
  1. Load sweep_results.csv generated by sweep_filters.py.
  2. Reshape into feature matrix X and per-action reward targets y[action].
  3. Train SupervisedFilterSelector on the training split.
  4. Evaluate on the validation split:
     - Compare selector against best fixed filter and oracle ceiling.
     - Report feature importances for acoustic interpretability.
  5. Save the trained model to models/selector.joblib.

Usage:
    python -m noise_suppression.train_selector \
        --sweep data/sweep_results.csv \
        --output models/selector.joblib
"""
from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from .constants import SAFETY_THRESHOLD_DB
from .features import FEATURE_NAMES
from .filters import ACTIONS
from .selector import SupervisedFilterSelector


def load_sweep_dataset(
    sweep_csv: Path | str,
    split: str | None = None,
) -> tuple[pd.DataFrame, np.ndarray, dict[str, np.ndarray], list[str]]:
    """Load sweep results and format into X and y_per_action.

    Returns
    -------
    meta_df : DataFrame with mixture_id, split, noise_category, snr_db (one row per mixture)
    X : (n_mixtures, n_features) feature matrix
    y_per_action : dict mapping action -> (n_mixtures,) SI-SDR improvements
    mixture_ids : list of mixture IDs in order
    """
    df = pd.read_csv(sweep_csv)
    if split is not None:
        df = df[df["split"] == split].copy()

    if df.empty:
        raise ValueError(f"No rows found in {sweep_csv}" + (f" for split '{split}'" if split else ""))

    # Feature column names
    feat_cols = [f"feat_{name}" for name in FEATURE_NAMES]
    for col in feat_cols:
        if col not in df.columns:
            raise ValueError(f"Missing expected feature column '{col}' in {sweep_csv}")

    # Unique mixture IDs in consistent order
    mixture_ids = list(df["mixture_id"].unique())

    # Extract unique feature row per mixture
    first_per_mix = df.drop_duplicates(subset=["mixture_id"]).set_index("mixture_id").loc[mixture_ids]
    X = first_per_mix[feat_cols].to_numpy(dtype=np.float32)

    # Pivot to get y_per_action: index=mixture_id, columns=action, values=si_sdr_improvement_db
    pivoted = df.pivot(index="mixture_id", columns="action", values="si_sdr_improvement_db").reindex(mixture_ids)

    y_per_action: dict[str, np.ndarray] = {}
    for action in ACTIONS:
        if action in pivoted.columns:
            y_per_action[action] = pivoted[action].to_numpy(dtype=np.float32)
        else:
            print(f"Warning: action '{action}' not found in sweep data")

    meta_df = first_per_mix[["split", "noise_category", "snr_db"]].reset_index()
    return meta_df, X, y_per_action, mixture_ids


def evaluate_selector_on_split(
    selector: SupervisedFilterSelector,
    X: np.ndarray,
    y_per_action: dict[str, np.ndarray],
    meta_df: pd.DataFrame,
) -> dict[str, Any]:
    """Evaluate selector decisions against ground-truth improvements."""
    n = len(X)
    selected_actions = selector.select_batch(X)

    # Extract achieved improvement per mixture
    achieved_gains = np.zeros(n, dtype=np.float32)
    for i, act in enumerate(selected_actions):
        if act in y_per_action:
            achieved_gains[i] = y_per_action[act][i]
        else:
            achieved_gains[i] = 0.0

    # Fixed filter baselines
    fixed_means = {act: float(np.mean(y_per_action[act])) for act in y_per_action}
    best_fixed_act = max(fixed_means, key=fixed_means.get)
    best_fixed_mean = fixed_means[best_fixed_act]

    # Oracle (best action per mixture)
    all_gains_matrix = np.column_stack([y_per_action[a] for a in y_per_action])
    oracle_per_mix = np.max(all_gains_matrix, axis=1)
    oracle_mean = float(np.mean(oracle_per_mix))

    selector_mean = float(np.mean(achieved_gains))

    # Action distribution
    action_counts = pd.Series(selected_actions).value_counts().to_dict()

    return {
        "n_samples": n,
        "selector_mean_gain_db": selector_mean,
        "best_fixed_filter": best_fixed_act,
        "best_fixed_mean_gain_db": best_fixed_mean,
        "oracle_mean_gain_db": oracle_mean,
        "gain_over_best_fixed_db": selector_mean - best_fixed_mean,
        "oracle_gap_recovered_fraction": (
            (selector_mean - best_fixed_mean) / (oracle_mean - best_fixed_mean + 1e-9)
            if oracle_mean > best_fixed_mean else 0.0
        ),
        "fixed_filters_mean_gains": fixed_means,
        "action_selection_distribution": action_counts,
    }


def train_and_evaluate(
    sweep_path: Path,
    output_path: Path,
    safety_threshold: float = SAFETY_THRESHOLD_DB,
) -> SupervisedFilterSelector:
    """Train selector on train split, validate on val split, save model."""
    print("=" * 60)
    print("Supervised Filter Selector Training")
    print("=" * 60)

    # Check available splits in sweep
    df_raw = pd.read_csv(sweep_path, nrows=500)
    splits = df_raw["split"].unique()
    has_val = "val" in splits
    has_train = "train" in splits

    train_split = "train" if has_train else None
    print(f"Loading training data (split={train_split}) from {sweep_path} ...")
    train_meta, X_train, y_train, _ = load_sweep_dataset(sweep_path, split=train_split)
    print(f"Loaded {len(X_train)} training clips across {len(FEATURE_NAMES)} features.")

    # Initialize and train
    selector = SupervisedFilterSelector(safety_threshold=safety_threshold)
    selector.fit(X_train, y_train)

    # Evaluate on validation split if present, else evaluate on train
    eval_split = "val" if has_val else train_split
    print(f"\nEvaluating selector on '{eval_split}' split ...")
    val_meta, X_val, y_val, _ = load_sweep_dataset(sweep_path, split=eval_split)
    metrics = evaluate_selector_on_split(selector, X_val, y_val, val_meta)

    print("\n" + "-" * 45)
    print("Validation Performance Summary:")
    print("-" * 45)
    print(f"  Clips evaluated          : {metrics['n_samples']}")
    print(f"  Selector mean delta SI-SDR: {metrics['selector_mean_gain_db']:+7.3f} dB")
    print(f"  Best fixed filter        : '{metrics['best_fixed_filter']}' ({metrics['best_fixed_mean_gain_db']:+7.3f} dB)")
    print(f"  Oracle ceiling           : {metrics['oracle_mean_gain_db']:+7.3f} dB")
    print(f"  Advantage over best fixed: {metrics['gain_over_best_fixed_db']:+7.3f} dB")
    print(f"  Oracle gap recovered     : {metrics['oracle_gap_recovered_fraction']*100:5.1f}%")

    print("\nAction Selection Distribution:")
    for act, cnt in sorted(metrics["action_selection_distribution"].items(), key=lambda x: -x[1]):
        pct = (cnt / metrics['n_samples']) * 100
        print(f"  {act:28s}: {cnt:4d} ({pct:5.1f}%)")

    # Top acoustic features per action
    print("\nTop Predictors per Filter (Feature Importance):")
    importances = selector.feature_importances()
    for act in ["spectral_subtraction", "wiener", "speech_bandpass", "notch_50hz", "log_mmse"]:
        if act in importances:
            top3 = [f"{name} ({weight:.2f})" for name, weight in importances[act][:3]]
            print(f"  {act:24s}: {', '.join(top3)}")

    # Save
    output_path.parent.mkdir(parents=True, exist_ok=True)
    selector.save(output_path)
    return selector


def main() -> None:
    parser = argparse.ArgumentParser(description="Train supervised filter selector from sweep results.")
    parser.add_argument("--sweep", type=Path, default=Path("data/sweep_results.csv"))
    parser.add_argument("--output", type=Path, default=Path("models/selector.joblib"))
    parser.add_argument("--safety-threshold", type=float, default=SAFETY_THRESHOLD_DB)
    args = parser.parse_args()

    train_and_evaluate(
        sweep_path=args.sweep,
        output_path=args.output,
        safety_threshold=args.safety_threshold,
    )


if __name__ == "__main__":
    main()
